import AppKit
import ApplicationServices
import Combine
import CryptoKit
import MacPocketCore

/// Watches the general pasteboard and keeps the clipboard history.
///
/// macOS has no pasteboard change notification, so `changeCount` is polled (only while the feature is on).
/// Writes MacPocket makes itself are remembered by change count and never re-recorded. Images are stored
/// as PNG named by content hash; with "save to disk" off they live only in memory.
@MainActor
final class ClipboardService: ObservableObject {
    static let shared = ClipboardService()
    #if DEBUG
    private let moduleProbe = ModuleServiceProbe("ClipboardService")
    #endif
    private(set) var moduleRunning = false

    @Published var settings: ClipboardSettings {
        didSet {
            guard settings != oldValue else { return }
            settings.save(to: .standard)
            apply(old: oldValue)
        }
    }
    @Published private(set) var history = ClipboardHistory()
    @Published private(set) var lastError: String?
    /// Set while a settings view records a new shortcut, so pressing it doesn't open the panel.
    var recordingShortcut = false { didSet { registerShortcut() } }
    @Published private(set) var shortcutRegistered = false

    #if DEBUG
    private let archive = ModuleRuntimeAudit.dataURL("clipboard").map { ClipboardArchive(directory: $0) } ?? .standard
    #else
    private let archive = ClipboardArchive.standard
    #endif
    private let pasteboard = NSPasteboard.general
    private var pollTimer: Timer?
    private var clearTimer: Timer?
    private var saveTask: Task<Void, Never>?
    private var lastChangeCount: Int
    private var ownChangeCount: Int?
    private var memoryImages: [String: Data] = [:]
    private let imageCache = NSCache<NSString, NSImage>()
    private var observers: [NSObjectProtocol] = []
    private lazy var hotKey = PocketGlobalHotKey { [weak self] in self?.togglePanel() }
    private lazy var panel = ClipboardPanelController(service: self)

    private static let pollInterval: TimeInterval = 0.4
    private static let concealedTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                                      "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    private init() {
        settings = ClipboardSettings.load(from: .standard)
        lastChangeCount = NSPasteboard.general.changeCount
    }

    /// Called once at launch.
    func stopForModule() {
        moduleRunning = false
        deactivate()
    }

    func start() {
        guard !moduleRunning, PocketModule.clipboard.isAvailable() else { return }
        moduleRunning = true
        if settings.enabled { activate() }
    }

    // MARK: Lifecycle

    private func apply(old: ClipboardSettings) {
        if settings.enabled != old.enabled {
            settings.enabled ? activate() : deactivate()
            return
        }
        guard settings.enabled else { return }
        if settings.saveToDisk != old.saveToDisk { switchStorage() }
        if settings.capacity < old.capacity || settings.retentionDays != old.retentionDays { enforceLimits() }
        if settings.shortcut != old.shortcut { registerShortcut() }
        if settings.clearClipboardAfterMinutes != old.clearClipboardAfterMinutes { scheduleClear() }
    }

    private func activate() {
        guard moduleRunning else { return }
        if settings.saveToDisk {
            do { history = try archive.load() } catch { report(String(localized: "Pano geçmişi okunamadı: \(error.localizedDescription)")) }
        }
        enforceLimits()
        lastChangeCount = pasteboard.changeCount
        pollTimer?.invalidate()
        let timer = Timer(timeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        pollTimer = timer
        observeSleepAndLock()
        registerShortcut()
    }

    private func deactivate() {
        pollTimer?.invalidate(); pollTimer = nil
        clearTimer?.invalidate(); clearTimer = nil
        observers.forEach { NSWorkspace.shared.notificationCenter.removeObserver($0); DistributedNotificationCenter.default().removeObserver($0) }
        observers = []
        hotKey.unregister()
        shortcutRegistered = false
        panel.close()
        flushSave()
    }

    private func registerShortcut() {
        guard moduleRunning, settings.enabled, !recordingShortcut else {
            hotKey.unregister()
            shortcutRegistered = false
            return
        }
        shortcutRegistered = hotKey.register(settings.shortcut)
    }

    private func observeSleepAndLock() {
        guard observers.isEmpty else { return }
        let clear: @Sendable (Notification) -> Void = { [weak self] _ in
            MainActor.assumeIsolated {
                guard let self, self.settings.clearClipboardOnSleepOrLock else { return }
                self.clearSystemClipboard()
            }
        }
        let workspace = NSWorkspace.shared.notificationCenter
        observers.append(workspace.addObserver(forName: NSWorkspace.willSleepNotification, object: nil, queue: .main, using: clear))
        observers.append(workspace.addObserver(forName: NSWorkspace.screensDidSleepNotification, object: nil, queue: .main, using: clear))
        observers.append(DistributedNotificationCenter.default().addObserver(forName: Notification.Name("com.apple.screenIsLocked"),
                                                                             object: nil, queue: .main, using: clear))
    }

    // MARK: Capture

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        if count == ownChangeCount { return }
        guard var capture = readPasteboard() else { return }
        if settings.cleanCopiedLinks, case let .link(url) = capture.content,
           let cleaned = LinkCleaner(extraParameters: settings.extraTrackingParameters).clean(url) {
            capture.content = .link(cleaned)
            writeToPasteboard(.link(cleaned), plain: true)
        }
        let outcome = history.record(capture, at: Date(), settings: settings)
        deleteImages(outcome.orphanedImages)
        if case .ignored = outcome.result { return }
        scheduleSave()
        scheduleClear()
    }

    private func readPasteboard() -> ClipboardCapture? {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        let source = NSWorkspace.shared.frontmostApplication
        // Passwords and one-time codes are marked concealed or transient by their writers: never read them.
        guard types.isDisjoint(with: Self.concealedTypes) else { return nil }
        func capture(_ content: ClipboardContent) -> ClipboardCapture {
            ClipboardCapture(content: content, sourceBundleID: source?.bundleIdentifier, sourceName: source?.localizedName)
        }
        if let files = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !files.isEmpty {
            return capture(.files(files))
        }
        if let text = pasteboard.string(forType: .string) {
            return ClipboardCapture.text(text, sourceBundleID: source?.bundleIdentifier, sourceName: source?.localizedName)
        }
        guard settings.keepImages else { return nil }
        // Check the raw size before decoding: converting a huge screenshot on the main thread would stall the
        // run loop that also serves MacPocket's event taps.
        let rawSize = [NSPasteboard.PasteboardType.png, .tiff].lazy.compactMap { self.pasteboard.data(forType: $0)?.count }.first ?? 0
        guard rawSize <= settings.maximumImageBytes * 4, let image = NSImage(pasteboard: pasteboard), let reference = storeImage(image) else { return nil }
        return capture(.image(reference))
    }

    private func storeImage(_ image: NSImage) -> ClipboardImageReference? {
        guard let tiff = image.tiffRepresentation, let bitmap = NSBitmapImageRep(data: tiff),
              let png = bitmap.representation(using: .png, properties: [:]), png.count <= settings.maximumImageBytes else { return nil }
        let name = SHA256.hash(data: png).prefix(16).map { String(format: "%02x", $0) }.joined() + ".png"
        if settings.saveToDisk {
            do { _ = try archive.storeImage(png, named: name) } catch { report(error.localizedDescription); return nil }
        } else {
            memoryImages[name] = png
        }
        return ClipboardImageReference(fileName: name, pixelWidth: bitmap.pixelsWide, pixelHeight: bitmap.pixelsHigh, byteCount: png.count)
    }

    func image(for reference: ClipboardImageReference) -> NSImage? {
        if let cached = imageCache.object(forKey: reference.fileName as NSString) { return cached }
        let data = memoryImages[reference.fileName] ?? (try? Data(contentsOf: archive.imageURL(reference.fileName)))
        guard let data, let image = NSImage(data: data) else { return nil }
        imageCache.setObject(image, forKey: reference.fileName as NSString)
        return image
    }

    // MARK: Using items

    /// Puts the item back on the pasteboard. `plain` drops formatting (and turns files into their paths).
    @discardableResult
    func copy(_ item: ClipboardItem, plain: Bool = false) -> Bool {
        guard moduleRunning, writeToPasteboard(item.content, plain: plain) else {
            report(String(localized: "Pano öğesi kopyalanamadı. Kaynak dosya silinmiş veya erişilemez olabilir."))
            return false
        }
        history.markUsed(item.id, at: Date())
        scheduleSave()
        scheduleClear()
        return true
    }

    /// Copies the item and, when allowed, pastes it into the app in front by sending ⌘V.
    func paste(_ item: ClipboardItem, plain: Bool = false) {
        guard copy(item, plain: plain) else { return }
        guard settings.pasteOnSelect else { return }
        guard AXIsProcessTrusted() else {
            report(String(localized: "Kopyalandı. Doğrudan yapıştırmak için MacPocket’e Erişilebilirlik izni ver; şimdilik ⌘V ile yapıştır."))
            return
        }
        // Let the panel give focus back before the keystroke arrives.
        let target = NSWorkspace.shared.frontmostApplication
        let pid = target?.processIdentifier
        let launch = target?.launchDate
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.08) { [weak self] in
            guard self?.moduleRunning == true, let pid, pid != getpid(),
                  NSWorkspace.shared.frontmostApplication?.processIdentifier == pid,
                  NSRunningApplication(processIdentifier: pid)?.launchDate == launch else { return }
            Self.sendPasteKeystroke()
        }
    }

    private static func sendPasteKeystroke() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let virtualKeyV: CGKeyCode = 9
        for keyDown in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: virtualKeyV, keyDown: keyDown)
            event?.flags = .maskCommand
            event?.post(tap: .cgAnnotatedSessionEventTap)
        }
    }

    func setPinned(_ pinned: Bool, _ item: ClipboardItem) {
        history.setPinned(pinned, for: item.id)
        scheduleSave()
    }

    func remove(_ item: ClipboardItem) {
        deleteImages(history.remove(item.id))
        scheduleSave()
    }

    func clearHistory(includingPinned: Bool) {
        deleteImages(history.clear(includingPinned: includingPinned))
        scheduleSave()
    }

    /// Removes tracking parameters from a stored link.
    func cleanLink(_ item: ClipboardItem) {
        guard case let .link(url) = item.content,
              let cleaned = LinkCleaner(extraParameters: settings.extraTrackingParameters).clean(url) else { return }
        history.replaceContent(of: item.id, with: .link(cleaned))
        scheduleSave()
    }

    func canClean(_ item: ClipboardItem) -> Bool {
        guard case let .link(url) = item.content else { return false }
        return LinkCleaner(extraParameters: settings.extraTrackingParameters).clean(url) != nil
    }

    @discardableResult
    private func writeToPasteboard(_ content: ClipboardContent, plain: Bool) -> Bool {
        // Resolve an image before clearing the current clipboard: its backing file may have disappeared.
        var resolvedImage: NSImage?
        if case let .image(reference) = content {
            resolvedImage = image(for: reference)
            guard resolvedImage != nil else { return false }
        }
        pasteboard.clearContents()
        let written: Bool
        switch content {
        case let .text(text): written = pasteboard.setString(text, forType: .string)
        case let .link(url):
            if !plain { _ = pasteboard.writeObjects([url as NSURL]) }
            written = pasteboard.setString(url.absoluteString, forType: .string)
        case let .files(urls):
            if plain { written = pasteboard.setString(urls.map(\.path).joined(separator: "\n"), forType: .string) }
            else { written = pasteboard.writeObjects(urls.map { $0 as NSURL }) }
        case .image:
            written = resolvedImage.map { pasteboard.writeObjects([$0]) } ?? false
        }
        ownChangeCount = pasteboard.changeCount
        lastChangeCount = pasteboard.changeCount
        return written
    }

    // MARK: Clearing the system clipboard

    private func scheduleClear() {
        clearTimer?.invalidate()
        clearTimer = nil
        guard settings.enabled, let minutes = settings.clearClipboardAfterMinutes else { return }
        let timer = Timer(timeInterval: Double(minutes) * 60, repeats: false) { [weak self] _ in
            MainActor.assumeIsolated { self?.clearSystemClipboard() }
        }
        RunLoop.main.add(timer, forMode: .common)
        clearTimer = timer
    }

    /// Empties the system clipboard; the history keeps its copy.
    func clearSystemClipboard() {
        guard moduleRunning else { return }
        pasteboard.clearContents()
        ownChangeCount = pasteboard.changeCount
        lastChangeCount = pasteboard.changeCount
    }

    // MARK: Storage

    private func enforceLimits() {
        deleteImages(history.prune(olderThan: settings.retentionDays, now: Date()))
        deleteImages(history.enforceCapacity(settings.capacity))
        scheduleSave()
    }

    private func switchStorage() {
        if settings.saveToDisk {
            for (name, data) in memoryImages { _ = try? archive.storeImage(data, named: name) }
            memoryImages = [:]
            flushSave()
        } else {
            // Keep what is shown, but move it into memory and erase it from disk.
            for item in history.items {
                if case let .image(reference) = item.content,
                   let data = try? Data(contentsOf: archive.imageURL(reference.fileName)) { memoryImages[reference.fileName] = data }
            }
            saveTask?.cancel()
            do { try archive.eraseAll() } catch { report(error.localizedDescription) }
        }
    }

    private func deleteImages(_ names: [String]) {
        guard !names.isEmpty else { return }
        for name in names {
            memoryImages[name] = nil
            imageCache.removeObject(forKey: name as NSString)
        }
        if settings.saveToDisk { archive.deleteImages(names) }
    }

    /// Coalesces bursts of copies into one write a second later.
    private func scheduleSave() {
        guard settings.saveToDisk else { return }
        saveTask?.cancel()
        saveTask = Task { [weak self] in
            try? await Task.sleep(for: .seconds(1))
            guard !Task.isCancelled else { return }
            self?.flushSave()
        }
    }

    func flushSave() {
        saveTask?.cancel()
        saveTask = nil
        guard settings.saveToDisk else { return }
        do { try archive.save(history) } catch { report(String(localized: "Pano geçmişi kaydedilemedi: \(error.localizedDescription)")) }
    }

    /// Deletes everything stored, including pinned items and images.
    func eraseEverything() {
        history = ClipboardHistory()
        memoryImages = [:]
        imageCache.removeAllObjects()
        saveTask?.cancel()
        do { try archive.eraseAll() } catch { report(error.localizedDescription) }
    }

    private func report(_ message: String) {
        lastError = message
    }

    func dismissError() { lastError = nil }

    // MARK: Panel

    func togglePanel() {
        guard moduleRunning, settings.enabled else { return }
        panel.toggle()
    }
}

